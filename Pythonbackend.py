class Car:
    # Конструктор класса
    def __init__(self, brand, color):
        self.brand = brand    # Атрибут (свойство) объекта
        self.color = color    # Атрибут (свойство) объекта
        self.is_moving = False

    # Метод (функция) класса
    def start_engine(self):
        self.is_moving = True
        print(f"Двигатель заведен! {self.brand} готов к поездке.")

# Создание объектов (экземпляров класса)

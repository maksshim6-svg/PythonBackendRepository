import time

def fetch_data(site_id):
    print(file=None)  # Для наглядности опустим, это обычный print
    print(f"Начало загрузки сайта {site_id}...")
    time.sleep(1)  # Полностью замораживает ВСЮ программу на 1 секунду
    print(f"Сайт {site_id} успешно загружен!")

# Три сайта будут грузиться строго по очереди: 1 + 1 + 1 = 3 секунды

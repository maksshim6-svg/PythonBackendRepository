import asyncio
import time

# 1. Объявляем асинхронную функцию (корутину)
async def fetch_data_async(site_id):
    print(f"Начало загрузки сайта {site_id}...")
    # asyncio.sleep не блокирует программу, а отдает управление обратно в Event Loop
    await asyncio.sleep(1)
    print(f"Сайт {site_id} успешно загружен!")

async def main():
    # 2. Формируем список задач для одновременного запуска
    tasks = [
        fetch_data_async(1),
        fetch_data_async(2),
        fetch_data_async(3)
    ]
    # 3. Запускаем их параллельно и ждем выполнения всех
    await asyncio.gather(*tasks)

# Запуск асинхронного цикла событий
start_time = time.time()
asyncio.run(main())
print(f"Все сайты загружены за {time.time() - start_time:.2f} сек.")
# Программа выполнится ВСЕГО за 1 секунду, так как паузы выполнялись параллельно!
